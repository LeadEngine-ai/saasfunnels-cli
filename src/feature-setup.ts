const catalogFeatureSchema = z
  .object({
    accessModel: z.enum(["boolean", "limit"]),
    aliases: z.array(z.string().regex(keyPattern)).max(50),
    description: z.string().max(4_000),
    evidence: z.array(evidenceSchema).max(16),
    key: z.string().regex(keyPattern),
    name: z.string().min(1).max(240),
    unit: z.string().min(1).max(80).nullable(),
  })
  .strict()
  .superRefine((feature, context) => {
    if ((feature.accessModel === "limit") !== Boolean(feature.unit)) {
      context.addIssue({
        code: "custom",
        message: "Only Limit Features declare a unit.",
        path: ["unit"],
      });
    }
  });

export const featureCatalogManifestSchema = z
  .object({
    environment: z.enum(["test", "production"]),
    features: z.array(catalogFeatureSchema).max(5_000),
    generatedBy: z.literal("saasfunnels features setup"),
    schemaVersion: z.literal(schemaVersion),
  })
  .strict()
  .superRefine((manifest, context) => {
    const keys = manifest.features.map((feature) => feature.key);
    if (new Set(keys).size !== keys.length) {
      context.addIssue({
        code: "custom",
        message: "Feature keys must be unique.",
        path: ["features"],
      });
    }
    const identities = manifest.features.flatMap((feature) => [
      feature.key,
      ...feature.aliases,
    ]);
    if (new Set(identities).size !== identities.length) {
      context.addIssue({
        code: "custom",
        message: "Feature keys and aliases cannot overlap.",
        path: ["features"],
      });
    }
  });

